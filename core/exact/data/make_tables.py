"""writes src/pdf/tables.rs: the fixed tables the pdf reader needs.

the data comes from published, permissively licensed sources:
    - glyph names to unicode: the adobe glyph list (bsd 3-clause), as fonttools ships it
    - standard, winansi and macroman encodings: the pdf 1.7 spec, annex d,
      as fonttools and python's codecs know them
    - widths of the standard 14 fonts: adobe's core 14 afm files, as reportlab ships them

run once with any python that has fonttools and reportlab installed:
    python make_tables.py ../src/pdf/tables.rs
the converter itself never runs python.
"""

from __future__ import annotations

import sys

from fontTools.agl import AGL2UV, LEGACY_AGL2UV, UV2AGL, toUnicode
from fontTools.encodings.StandardEncoding import StandardEncoding
from reportlab.pdfbase import pdfmetrics

STANDARD_14 = [
    "Helvetica", "Helvetica-Bold", "Helvetica-Oblique", "Helvetica-BoldOblique",
    "Times-Roman", "Times-Bold", "Times-Italic", "Times-BoldItalic",
    "Courier", "Courier-Bold", "Courier-Oblique", "Courier-BoldOblique",
    "Symbol", "ZapfDingbats",
]  # fmt: skip


def glyph_name_for(char: str) -> str:
    return UV2AGL.get(ord(char), f"uni{ord(char):04X}")


def win_ansi_names() -> list[str]:
    names = []
    for code in range(256):
        try:
            names.append(glyph_name_for(bytes([code]).decode("cp1252")))
        except UnicodeDecodeError:
            names.append("")
    return names


def mac_roman_names() -> list[str]:
    return [glyph_name_for(bytes([code]).decode("mac_roman")) for code in range(256)]


def standard_names() -> list[str]:
    return [name if name != ".notdef" else "" for name in StandardEncoding]


def rust_string(text: str) -> str:
    return '"' + "".join(c if c.isascii() and c.isprintable() and c not in '"\\' else f"\\u{{{ord(c):x}}}" for c in text) + '"'


def names_array(name: str, names: list[str]) -> str:
    body = ",\n".join(f"    {rust_string(n)}" for n in names)
    return f"pub(crate) const {name}: [&str; 256] = [\n{body},\n];\n"


def glyph_list() -> str:
    # fonttools' toUnicode looks names up in the whole legacy list, not only the shorter aglfn
    rows = sorted((name, toUnicode(name)) for name in set(LEGACY_AGL2UV) | set(AGL2UV))
    body = ",\n".join(f"    ({rust_string(n)}, {rust_string(text)})" for n, text in rows if text)
    return f"/// adobe glyph list, sorted by name for a binary search\npub(crate) const GLYPH_LIST: &[(&str, &str)] = &[\n{body},\n];\n"


def standard_widths() -> str:
    names = win_ansi_names()
    parts = ["/// widths in 1/1000 em of the standard 14 fonts for each winansi code (0: no glyph)",
             "pub(crate) const STANDARD_14_WIDTHS: &[(&str, [u16; 256])] = &["]  # fmt: skip
    for base in STANDARD_14:
        face = pdfmetrics.getFont(base).face
        widths = [int(face.glyphWidths.get(name, 0)) if name else 0 for name in names]
        parts.append(f"    ({rust_string(base)}, [{', '.join(str(w) for w in widths)}]),")
    parts.append("];\n")
    return "\n".join(parts)


def main() -> None:
    out = [
        "//! fixed tables for reading pdf fonts. generated by data/make_tables.py, do not edit by hand.",
        "//! sources: the adobe glyph list (bsd 3-clause), the pdf 1.7 encodings (annex d) and",
        "//! adobe's core 14 font metrics, all freely redistributable.",
        "",
        names_array("STANDARD_ENCODING", standard_names()),
        names_array("WIN_ANSI_ENCODING", win_ansi_names()),
        names_array("MAC_ROMAN_ENCODING", mac_roman_names()),
        glyph_list(),
        standard_widths(),
    ]
    with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(out))


if __name__ == "__main__":
    main()
