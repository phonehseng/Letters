//! character widths of the standard pdf fonts, for measuring text.
//!
//! source: the Adobe Core 14 AFM font metrics files (Helvetica,
//! Helvetica-Bold, Times-Roman, Times-Bold, Times-Italic,
//! Times-BoldItalic, Courier), which Adobe publishes for free use, read
//! out for each WinAnsiEncoding code. they were cross-checked against the
//! widths pdfium reports for its built-in fonts, which agree except for a
//! handful of rarely used signs (plus-minus, micro, middle dot, divide,
//! macron, soft hyphen) where pdfium substitutes a symbol glyph; for
//! those the Adobe values are used.
//!
//! widths are in thousandths of the font size. each table starts at
//! code 32 (space) and ends at code 255. the oblique helvetica fonts
//! share the upright widths, and all courier fonts are 600 throughout.

/// the first character code in each table.
